  write(*,*)
  write(*,*) " ---------------------------------------------------------------------"
  write(*,*)
  write(*,*) "  Edge based data construction and check." 
  write(*,*)

   left = 1
   rght = 2

     ix = 1
     iy = 2
     iz = 3

