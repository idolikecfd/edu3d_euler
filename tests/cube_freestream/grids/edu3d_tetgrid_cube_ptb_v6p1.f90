  integer , dimension(4,3)   :: loc_nghbr
  integer , dimension(6,2)   :: loc_edge
  integer , dimension(6,2,3) :: loc_face
  integer                    :: left, rght ! Left and right face of an edge in tet.

  integer                    :: max_nnghbrs
  integer                    :: i, j, k, m
  integer                    :: ix, iy, iz
  logical                    :: found

  real(dp), dimension(3)                :: edge_vector
  real(dp), dimension(3)                :: directed_area_contribution
  real(dp)                              :: dxjk_dot_njk

! Two dual face normals of edge in a tetrahedron.
  real(dp), dimension(3)                :: normal1, normal2

