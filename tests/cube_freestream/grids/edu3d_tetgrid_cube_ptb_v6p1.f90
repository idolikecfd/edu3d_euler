  nnghbrs = 0

  allocate(  nghbr(nnodes, 50 ) ) !Assume nnghbrs < 51.
  nghbr = 0

 !-------------------------------------------------
 ! Find edge-connected neghbr nodes within a tetrahedron.
  do i = 1, ntet

  !-------------------------------------------------
  ! Loop over the nodes of tetrahedron i.
   do k = 1, 4

     n1 = tet(i,k)
     
   !-------------------------------------------------
   ! Loop over the rest of nodes.
    do j = 1, 3
     n2 = tet(i,loc_nghbr(k,j))

     if ( nnghbrs(n1) == 0 ) then

      nnghbrs(n1) = 1
      nghbr(n1,1) = n2

     else

     !Check if the neighbor is already added.
      found = .false.
      do m = 1, nnghbrs(n1)
       if (n2 == nghbr(n1,m)) then
        found = .true.
        exit
       endif
      end do

     !If not added yet, add it to the list.
      if (.not.found) then
       nnghbrs(n1) = nnghbrs(n1) + 1
       nghbr(n1,nnghbrs(n1)) = n2
      endif

     endif

    end do
   !-------------------------------------------------
   ! End of Loop over the rest of nodes.

   end do
